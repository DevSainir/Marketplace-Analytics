"""Generating activation codes, and redeeming one into an organisation.

The commercial flow this implements has one deliberate property: **money never
touches this system.** A customer pays us by bank transfer, we generate a code
and hand it over, they enter it. That keeps payment processing, invoicing and
tax out of a codebase that has no business holding any of it, at the cost of one
manual step per customer — which at this scale is a message, not a burden.

Redemption is the only place an organisation is ever created, and it does four
things that must all happen or none: create the organisation, make the redeemer
its owner, start the subscription, and mark the code used. They share the
request's transaction, so a failure anywhere leaves the code unredeemed and the
customer able to try again — rather than an ownerless organisation nobody can
reach and a code that will not work twice.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime, timedelta

from sqlalchemy.exc import IntegrityError

from src.core.config import settings
from src.core.exceptions import ConflictError, PermissionDeniedError
from src.core.logging import get_logger
from src.core.security import generate_opaque_secret, hash_opaque_secret
from src.modules.organizations.models import MemberRole
from src.modules.organizations.repos import (
    ActivationCodeRepository,
    MembershipRepository,
    OrganizationRepository,
    SubscriptionRepository,
)
from src.modules.organizations.schemas import (
    ActivationCodeCreated,
    ActivationCodeRead,
    OrganizationRead,
)

logger = get_logger(__name__)

#: Bytes of entropy in an activation code. Shorter than a refresh secret
#: because a human retypes this one out of a chat message, and 192 bits is
#: still unguessable by any margin that matters.
_CODE_BYTES = 24


class ActivationService:
    """Issues activation codes (dev) and redeems them into organisations."""

    def __init__(
        self,
        *,
        code_repo: ActivationCodeRepository,
        organization_repo: OrganizationRepository,
        membership_repo: MembershipRepository,
        subscription_repo: SubscriptionRepository,
    ) -> None:
        """Store the injected repository collaborators."""
        self._codes = code_repo
        self._organizations = organization_repo
        self._memberships = membership_repo
        self._subscriptions = subscription_repo

    # ------------------------------------------------------------------ #
    # Issuing (dev only)
    # ------------------------------------------------------------------ #
    async def generate_code(
        self,
        *,
        note: str,
        valid_for_days: int | None,
        subscription_days: int,
        created_by_user_id: uuid.UUID,
    ) -> ActivationCodeCreated:
        """Generate a single-use activation code.

        Args:
            note: Who it was sold to — the only record, since billing is
                off-system.
            valid_for_days: How long it stays redeemable; ``None`` = forever.
            subscription_days: The term it buys.
            created_by_user_id: The dev generating it.

        Returns:
            The code, in the only response that will ever carry its value.
        """
        code = generate_opaque_secret(_CODE_BYTES)
        expires_at = (
            datetime.now(UTC) + timedelta(days=valid_for_days)
            if valid_for_days is not None
            else None
        )
        row = await self._codes.create(
            code_hash=hash_opaque_secret(code),
            note=note,
            subscription_days=subscription_days,
            expires_at=expires_at,
            created_by_user_id=created_by_user_id,
        )
        logger.info("Activation code %s generated by user %s.", row.id, created_by_user_id)
        return ActivationCodeCreated(
            id=row.id,
            code=code,
            note=note,
            expires_at=expires_at,
            subscription_days=subscription_days,
        )

    async def list_codes(self) -> list[ActivationCodeRead]:
        """List every generated code, newest first (values never included)."""
        rows = await self._codes.list_all()
        return [
            ActivationCodeRead(
                id=row.id,
                note=row.note,
                expires_at=row.expires_at,
                used_at=row.used_at,
                organization_id=row.organization_id,
                created_at=row.created_at,
            )
            for row in rows
        ]

    # ------------------------------------------------------------------ #
    # Redeeming
    # ------------------------------------------------------------------ #
    async def redeem(self, *, code: str, user_id: uuid.UUID, email: str) -> OrganizationRead:
        """Redeem a code, creating the caller's organisation and owning it.

        Args:
            code: The code as the customer typed it (whitespace tolerated —
                it arrives pasted out of a chat message).
            user_id: The redeeming account.
            email: Their email, which becomes the organisation's initial name
                so nothing has to be typed on this screen.

        Returns:
            The created organisation.

        Raises:
            PermissionDeniedError: The code is unknown, already used, expired,
                or lost the race to consume it. One message for all of them: a
                caller holding a wrong code learns nothing about which wrong
                thing it is, and an attacker enumerating codes gets no signal
                to steer by.
            ConflictError: The caller already belongs to an organisation.
        """
        existing = await self._memberships.get_for_user(user_id)
        if existing is not None:
            raise ConflictError("Этот аккаунт уже состоит в организации.")

        row = await self._codes.get_by_hash(hash_opaque_secret(code.strip()))
        now = datetime.now(UTC)
        if row is None or row.used_at is not None or (row.expires_at and row.expires_at <= now):
            # Deliberately indistinguishable. Logged at INFO with the reason so
            # support can tell a customer which of the three it was, without the
            # response saying it.
            logger.info(
                "Rejected activation attempt by user %s (known=%s, used=%s, expired=%s).",
                user_id,
                row is not None,
                bool(row and row.used_at),
                bool(row and row.expires_at and row.expires_at <= now),
            )
            raise PermissionDeniedError("Ключ активации недействителен.")

        # Claim the code BEFORE building anything. The check above is a
        # read-then-write, and two DIFFERENT accounts redeeming the same code in
        # the same moment both pass it — one code sold once would create two
        # paid organisations, with nothing afterwards able to say which was
        # legitimate. The conditional UPDATE decides that race in the database,
        # and the loser is told the code is invalid, which by then it is.
        # Claiming first also means a lost race leaves no orphan organisation:
        # nothing has been created yet.
        if not await self._codes.claim(row.id, used_at=now, used_by_user_id=user_id):
            logger.info("User %s lost the race to redeem activation code %s.", user_id, row.id)
            raise PermissionDeniedError("Ключ активации недействителен.")

        organization = await self._organizations.create(name=email, is_primary=False)
        try:
            await self._memberships.create(
                organization_id=organization.id,
                user_id=user_id,
                role=MemberRole.OWNER,
            )
        except IntegrityError as exc:
            # Two redemptions racing on the same account: the UNIQUE on
            # memberships.user_id catches the loser here, and it means the same
            # thing as the pre-check above.
            raise ConflictError("Этот аккаунт уже состоит в организации.") from exc

        await self._subscriptions.create(
            organization_id=organization.id,
            started_at=now,
            expires_at=now + timedelta(days=row.subscription_days),
            grace_days=settings.subscription_grace_days,
        )
        await self._codes.attach_organization(row.id, organization_id=organization.id)
        logger.info(
            "User %s activated organisation %s for %d days.",
            user_id,
            organization.id,
            row.subscription_days,
        )
        return OrganizationRead.model_validate(organization)
